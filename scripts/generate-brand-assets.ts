// Regenerates src/brand-assets.ts from the binary files in assets/.
// Assets are embedded (base64) so every runtime — Bun, the container and the
// Cloudflare Worker — can serve them without filesystem access.
//   bun scripts/generate-brand-assets.ts          write
//   bun scripts/generate-brand-assets.ts --check  fail if out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const ASSETS: Array<[route: string, file: string, contentType: string]> = [
  ["/favicon.svg", "assets/brand/favicon.svg", "image/svg+xml"],
  ["/favicon.ico", "assets/brand/favicon.ico", "image/x-icon"],
  ["/assets/fonts/ibm-plex-mono-latin-400-normal.woff2", "assets/fonts/ibm-plex-mono-latin-400-normal.woff2", "font/woff2"],
  ["/assets/fonts/ibm-plex-mono-latin-500-normal.woff2", "assets/fonts/ibm-plex-mono-latin-500-normal.woff2", "font/woff2"],
];

const entries = ASSETS.map(([route, file, type]) => `  [${JSON.stringify(route)}, { contentType: ${JSON.stringify(type)}, base64: ${JSON.stringify(readFileSync(file).toString("base64"))} }],`);
const output = `// Generated by scripts/generate-brand-assets.ts. Do not edit by hand.
// IBM Plex Mono is licensed under the SIL Open Font License 1.1 (assets/fonts/IBM-Plex-Mono-OFL.txt).
export interface BrandAsset { contentType: string; base64: string }

export const BRAND_ASSETS: ReadonlyMap<string, BrandAsset> = new Map<string, BrandAsset>([
${entries.join("\n")}
]);
`;
const target = "src/brand-assets.ts";
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) {
    console.error(`${target} is out of date; run bun scripts/generate-brand-assets.ts`);
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target} (${ASSETS.length} assets)`);
}
